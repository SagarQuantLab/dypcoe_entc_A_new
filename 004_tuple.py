# TUPLE
# (), ordered, index, duplicates allowed, immutable

my_tuple = (1, 3, 2, 6, 8, 8)

# first element access
print(my_tuple[0])

# first tow element access
print(my_tuple[0:2])

# first and third element
print(my_tuple[0:3:2])

# last element
print(my_tuple[-1])

# reverse tuple
print(my_tuple[::-1])

